DO $$
BEGIN
	CREATE TABLE PERFIL (
		PERFIL_ID NUMERIC(7) NOT NULL,
		DESCRICAO VARCHAR(200),
		IND_ADMIN BOOLEAN,
		IND_REGULAR BOOLEAN,
		IND_SUPORTE BOOLEAN,
		IND_VENDA BOOLEAN,
		PRIMARY KEY (PERFIL_ID)
	);
	
	CREATE SEQUENCE PERFIL_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;