DO $$
BEGIN
	CREATE TABLE PEDIDO_PRODUTO (
		PEDIDOPRODUTO_ID NUMERIC(7) NOT NULL,
		PEDIDO_ID NUMERIC(7) NOT NULL,
		PRODUTO_ID NUMERIC(7) NOT NULL,
		QUANTIDADE NUMERIC(7),
