DO $$
BEGIN
	CREATE TABLE PEDIDO (
		PEDIDO_ID NUMERIC(7) NOT NULL,
		USUARIO_ID NUMERIC(7) NOT NULL,
		COMPRADOR_ID NUMERIC(7) NOT NULL,
		CODIGO_PEDIDO VARCHAR(11),
		PRECO_TOTAL NUMERIC(7,2),
		DATA_PEDIDO TIMESTAMP,
		PRIMARY KEY (PEDIDO_ID)
	);
	
	CREATE SEQUENCE PEDIDO_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
	CREATE SEQUENCE CODIGOPEDIDO_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;