DO $$
BEGIN
	CREATE TABLE FORNECEDOR (
		FORNECEDOR_ID NUMERIC(7) NOT NULL,
		NEGOCIO_ID NUMERIC(7) NOT NULL,
		CODIGO VARCHAR(100),
		NOME VARCHAR(200),
		NOME_FANTASIA VARCHAR(200),
		CNPJ VARCHAR(200),
		ENDERECO VARCHAR(200),
		IMAGEM VARCHAR(500),
		LAYOUT_EXCEL VARCHAR(200),
		IND_LAYOUT_DEFAULT BOOLEAN,
		PRIMARY KEY (FORNECEDOR_ID)
	);
	
	CREATE SEQUENCE FORNECEDOR_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;