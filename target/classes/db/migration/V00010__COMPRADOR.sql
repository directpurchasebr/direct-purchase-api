DO $$
BEGIN
	CREATE TABLE COMPRADOR (
		COMPRADOR_ID NUMERIC(7) NOT NULL,
		NEGOCIO_ID NUMERIC(7) NOT NULL,
		CODIGO VARCHAR(100),
		NOME VARCHAR(200),
		ENDERECO VARCHAR(200),
		CNPJ VARCHAR(200),
		IMAGEM VARCHAR(500),
		PRIMARY KEY (COMPRADOR_ID)
	);
	
	CREATE SEQUENCE COMPRADOR_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;