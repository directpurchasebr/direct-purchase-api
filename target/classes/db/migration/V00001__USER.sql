DO $$
BEGIN
	CREATE TABLE USUARIO (
		USUARIO_ID NUMERIC(7) NOT NULL,
		PERFIL_ID NUMERIC(7) NOT NULL,
		NOME VARCHAR(200),
		EMAIL VARCHAR(200),
		LOGIN VARCHAR(200),
		SENHA VARCHAR(200),
		DATA_NASCIMENTO DATE,
		DATA_MODIF TIMESTAMP,
		DATA_CADASTRO TIMESTAMP,
		IND_ESTOQUE BOOLEAN,
		PRIMARY KEY (USUARIO_ID)
	);
	
	CREATE SEQUENCE USUARIO_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;
 