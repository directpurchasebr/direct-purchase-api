DO $$
BEGIN
	CREATE TABLE ESTOQUE (
		ESTOQUE_ID NUMERIC(7) NOT NULL,
		USUARIO_ID NUMERIC(7) NOT NULL,
		PRODUTO_ID NUMERIC(7) NOT NULL, 
		QUANTIDADE NUMERIC(7),
		PRECO NUMERIC(7,2),
		PRIMARY KEY (ESTOQUE_ID)
	);
	
	CREATE SEQUENCE ESTOQUE_SEQ INCREMENT BY 1 START WITH 1 NO CYCLE;
 
	EXCEPTION 
		WHEN duplicate_table THEN NULL;
	    WHEN duplicate_object THEN NULL;
	    WHEN duplicate_column THEN NULL;
END
$$;